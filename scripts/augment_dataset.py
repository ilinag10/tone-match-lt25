import os
import glob
import logging
import numpy as np
import pandas as pd
import librosa
import soundfile as sf
from scipy.signal import butter, sosfilt
import sys
from pathlib import Path
sys.path.append(str(Path(__file__).resolve().parent.parent))
import src.feature_extractor
from download_stems import clean_string

# Setup logging
logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")

# Paths
INPUT_CSV = "data/anchors.csv"
AUDIO_DIR = "data/audio_stems"
AUG_AUDIO_DIR = "data/audio_stems_augmented"
OUTPUT_CSV = "data/anchors_features_augmented.csv"

os.makedirs(AUG_AUDIO_DIR, exist_ok=True)

def apply_gain_offset(y: np.ndarray, db_offset: float) -> np.ndarray:
    """Applies gain adjustment in dB."""
    #deltaDB = 20 * log(k); k = (Anew/Aorig) => k = 10^(deltaDB/20)
    factor = 10.0 ** (db_offset / 20.0)
    return y * factor

def apply_eq_tilt(y: np.ndarray, sr: int, tilt_type: str, alpha: float = 0.7) -> np.ndarray:
    """Applies a gentle high-pass or low-pass spectral tilt filter with dry/wet blending."""
    if tilt_type == "high_pass":
        sos = butter(1, 150, btype="highpass", fs=sr, output="sos")
    elif tilt_type == "low_pass":
        sos = butter(1, 6000, btype="lowpass", fs=sr, output="sos")
    else:
        # Early return: returns unmodified audio array immediately
        return y

    # Only reached if tilt_type is 'high_pass' or 'low_pass'
    w = sosfilt(sos, y)
    return alpha * y + (1.0 - alpha) * w


def apply_pitch_shift(y: np.ndarray, sr: int, n_steps: int) -> np.ndarray:
    """Shifts pitch by n_steps semitones."""
    return librosa.effects.pitch_shift(y=y, sr=sr, n_steps=n_steps)

def generate_augmentations(audio_path: str, output_dir: str):
    """
    Generates 3-4 augmented audio variations for a given audio stem:
    1. Gain Offset (-1.5 dB)
    2. Gain Offset (+1.5 dB) + High Tilt
    3. Pitch Shift (+1 semitone)
    4. Pitch Shift (-1 semitone) + Low Tilt
    """
    y, sr = librosa.load(audio_path, sr=22050, mono=True)
    base_name = os.path.splitext(os.path.basename(audio_path))[0]

    aug_files = []

    # Original
    aug_files.append((y, sr, f"{base_name}_orig.wav", "none"))

    # Variation 1: Gain -1.5 dB
    y_aug1 = apply_gain_offset(y, -1.5)
    aug_files.append((y_aug1, sr, f"{base_name}_aug_gain_neg.wav", "gain_neg"))

    # Variation 2: Gain +1.5 dB + High Tilt
    y_aug2 = apply_gain_offset(y, 1.5)
    y_aug2 = apply_eq_tilt(y_aug2, sr, "high_pass")
    aug_files.append((y_aug2, sr, f"{base_name}_aug_gain_pos_tilt_hi.wav", "gain_pos_tilt_hi"))

    # Variation 3: Pitch Shift +1 semitone
    y_aug3 = apply_pitch_shift(y, sr, n_steps=1)
    aug_files.append((y_aug3, sr, f"{base_name}_aug_pitch_pos.wav", "pitch_pos"))

    # Variation 4: Pitch Shift -1 semitone + Low Tilt
    y_aug4 = apply_pitch_shift(y, sr, n_steps=-1)
    y_aug4 = apply_eq_tilt(y_aug4, sr, "low_pass")
    aug_files.append((y_aug4, sr, f"{base_name}_aug_pitch_neg_tilt_lo.wav", "pitch_neg_tilt_lo"))

    saved_paths = []
    for data, sample_rate, filename, aug_type in aug_files:
        out_path = os.path.join(output_dir, filename)
        sf.write(out_path, data, sample_rate)
        saved_paths.append((out_path, aug_type))

    return saved_paths

def main():
    if not os.path.exists(INPUT_CSV):
        logging.error(f"Input CSV not found at {INPUT_CSV}")
        return

    df_anchors = pd.read_csv(INPUT_CSV)
    logging.info(f"Loaded {len(df_anchors)} anchor presets from {INPUT_CSV}")

    augmented_dataset = []

    for idx, row in df_anchors.iterrows():
        clean_title = clean_string(row["song_title"])
        clean_artist = clean_string(row["artist"])

    # Target exact filename pattern generated by download_stems.py: "000_artist_title.wav"
        expected_filename = f"{idx:03d}_{clean_artist}_{clean_title}.wav"
        audio_stem_path = os.path.join(AUDIO_DIR, expected_filename)

        # Primary check: Exact path match
        if not os.path.exists(audio_stem_path):
            # Fallback search: Match by title string anywhere in filename
            pattern = os.path.join(AUDIO_DIR, f"*{clean_title}*.wav")
            matching_files = glob.glob(pattern)
            audio_stem_path = matching_files[0] if matching_files else None

        if not audio_stem_path or not os.path.exists(audio_stem_path):
            logging.warning(f"[{idx+1}/{len(df_anchors)}] No stem found for '{clean_title}'. Skipping...")
            continue

        logging.info(f"Augmenting [{idx+1}/{len(df_anchors)}]: {clean_artist} - {clean_title}")


        # Step 1: Generate augmented audio variations
        aug_results = generate_augmentations(audio_stem_path, AUG_AUDIO_DIR)

        # Step 2: Pass all original & augmented files through feature extractor
        for aug_audio_path, aug_type in aug_results:
            features = src.feature_extractor.extract_raw_blueprint_features(aug_audio_path)

            # Combine original preset labels + metadata + extracted features
            combined_row = row.to_dict()
            combined_row["aug_type"] = aug_type
            combined_row["augmented_audio_path"] = aug_audio_path
            combined_row.update(features)

            augmented_dataset.append(combined_row)

    # Save expanded dataset
    df_augmented = pd.DataFrame(augmented_dataset)
    df_augmented.to_csv(OUTPUT_CSV, index=False)
    logging.info(f"Successfully generated {len(df_augmented)} feature vectors.")
    logging.info(f"Augmented dataset saved to: {OUTPUT_CSV}")


if __name__ == "__main__":
    main()